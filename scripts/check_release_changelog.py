"""Script to verify that an automated release PR has not fallen out of sync with main.

When a release PR is generated by `create-release-pr.yml`, all unreleased changelog
entries at that moment are batched into the release version document and deleted from
`.changes/unreleased/`. If any subsequent PRs containing changelog entries merge into
`main` while the release PR is pending, those changes will ship with the release but
their changelog entries will remain orphaned in `.changes/unreleased/` on `main`.

This script checks that:
1. No new unreleased changelog entries have landed on `origin/main` since the release
   branch diverged from `main`.
2. The release branch itself does not contain unbatched changelog entries in
   `.changes/unreleased/`.
"""

import argparse
import subprocess
import sys
from pathlib import Path


def get_new_unreleased_entries_on_main(
    pr_head: str,
    *,
    base_branch: str = "origin/main",
    repo_dir: Path | None = None,
) -> list[str]:
    """Find unreleased changelog entries added to base_branch after pr_head diverged."""
    cwd = str(repo_dir) if repo_dir else None
    try:
        merge_base = subprocess.check_output(
            ["git", "merge-base", pr_head, base_branch],
            cwd=cwd,
            text=True,
            stderr=subprocess.PIPE,
        ).strip()
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(
            f"Failed to find merge-base between {pr_head} and {base_branch}: {exc.stderr}"
        ) from exc

    diff_output = subprocess.check_output(
        [
            "git",
            "diff",
            "--name-only",
            "--diff-filter=d",
            f"{merge_base}..{base_branch}",
            "--",
            ".changes/unreleased/",
        ],
        cwd=cwd,
        text=True,
    ).strip()

    if not diff_output:
        return []

    return [
        line.strip()
        for line in diff_output.splitlines()
        if line.strip() and not line.strip().endswith(".gitkeep")
    ]


def get_unreleased_entries_on_branch(changes_dir: Path) -> list[str]:
    """Find any unbatched entries in .changes/unreleased on the current branch."""
    unreleased_dir = changes_dir / "unreleased"
    if not unreleased_dir.is_dir():
        return []

    return [
        p.name for p in unreleased_dir.iterdir() if p.is_file() and p.name != ".gitkeep"
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--pr-head",
        required=True,
        help="The commit SHA of the release PR head.",
    )
    parser.add_argument(
        "--base-branch",
        default="origin/main",
        help="The target base branch (default: origin/main).",
    )
    parser.add_argument(
        "--repo-dir",
        type=Path,
        default=None,
        help="Optional path to repository root (defaults to script parent directory).",
    )
    args = parser.parse_args()

    repo_root = args.repo_dir if args.repo_dir else Path(__file__).resolve().parents[1]
    changes_dir = repo_root / ".changes"

    errors: list[str] = []

    # Check 1: entries on main merged after the release PR was cut
    try:
        new_on_main = get_new_unreleased_entries_on_main(
            args.pr_head,
            base_branch=args.base_branch,
            repo_dir=repo_root,
        )
        if new_on_main:
            errors.append(
                f"New unreleased changelog entries were merged into {args.base_branch} "
                "after this release PR was created:\n"
                + "\n".join(f"  - {entry}" for entry in new_on_main)
            )
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    # Check 2: unbatched entries on the release branch itself
    unreleased_on_branch = get_unreleased_entries_on_branch(changes_dir)
    if unreleased_on_branch:
        errors.append(
            "Unbatched changelog entries still exist on this release branch:\n"
            + "\n".join(
                f"  - .changes/unreleased/{entry}" for entry in unreleased_on_branch
            )
        )

    if errors:
        print("::error::Release PR changelog parity check failed!\n")
        for err in errors:
            print(f"{err}\n")
        print(
            "Merging this release PR would cause those changes to be included in the release "
            "without being recorded in CHANGELOG.md.\n\n"
            "To fix this, close this PR and re-trigger the 'Create release PR' workflow."
        )
        return 1

    print("Success: Release PR is in sync with unreleased changelog entries.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
